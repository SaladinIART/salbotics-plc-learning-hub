"""Build the search index used by the start page search box.

Reads the lesson list (static/hub-flow.js), each lesson's "In 30 seconds"
points and topics (title, subtitle, plain-language text), and the glossary
(static/hub-ui.js). Adds Bahasa Malaysia and German text from static/lang/*.json
under "tr" so search works in the chosen language. Writes static/search-index.js.
Standard library only.

Usage:
    python scripts/build_search_index.py          # write the index
    python scripts/build_search_index.py --check  # fail if it is out of date
"""

import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATIC = ROOT / "static"
OUTPUT = STATIC / "search-index.js"


def text(fragment):
    fragment = re.sub(r"<svg.*?</svg>", " ", fragment, flags=re.S)
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", fragment))).strip()


def lessons():
    flow = (STATIC / "hub-flow.js").read_text(encoding="utf-8")
    stages = dict(re.findall(r'\{ id: "([a-z]+)", name: "([^"]+)" \}', flow))
    found = re.findall(
        r'file: "([a-z0-9-]+\.html)", stage: "([a-z]+)", title: "([^"]+)",\s*blurb: "([^"]+)"', flow)
    return [{"file": f, "stage": stages[s], "title": t, "blurb": b} for f, s, t, b in found]


LANGS = ("ms", "de")


def translations():
    out = {}
    for code in LANGS:
        path = STATIC / "lang" / f"{code}.json"
        out[code] = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    return out


def add_tr(item, tr, keys):
    """keys: {field: translation key or list of keys}. Adds item["tr"][lang][field]."""
    found = {}
    for code in LANGS:
        fields = {}
        for field, key in keys.items():
            if isinstance(key, list):
                values = [text(tr[code][k]) for k in key if k in tr[code]]
                if values and len(values) == len(key):
                    fields[field] = values
            elif key and key in tr[code]:
                fields[field] = text(tr[code][key])
        if fields:
            found[code] = fields
    if found:
        item["tr"] = found
    return item


def topics(page_html, tr):
    out = []
    for m in re.finditer(r'<section id="([^"]+)"[^>]*>(.*?)</section>', page_html, re.S):
        sid, body = m.group(1), m.group(2)
        heading = re.search(
            r'<div class="panel-heading">\s*<h2(?: data-i18n="([^"]+)")?>(.*?)</h2>\s*(?:<span>(.*?)</span>)?', body, re.S)
        if not heading:
            continue
        plain = re.search(r'<p class="plain-text"(?: data-i18n="([^"]+)")?>(.*?)</p>', body, re.S)
        out.append(add_tr({
            "id": sid,
            "title": text(heading.group(2)),
            "sub": text(heading.group(3) or ""),
            "plain": text(plain.group(2)) if plain else "",
        }, tr, {"title": heading.group(1), "plain": plain.group(1) if plain else None}))
    return out


def build():
    index = {"lessons": [], "topics": [], "words": []}
    tr = translations()
    for n, lesson in enumerate(lessons(), start=1):
        page = (STATIC / lesson["file"]).read_text(encoding="utf-8")
        summary = re.search(r'<div class="hub-summary".*?<ul>(.*?)</ul>', page, re.S)
        items = re.findall(r'<li(?: data-i18n="([^"]+)")?>(.*?)</li>', summary.group(1), re.S) if summary else []
        points = [text(li) for _, li in items]
        base = lesson["file"][:-len(".html")]
        index["lessons"].append(add_tr(dict(lesson, number=n, summary=points), tr, {
            "title": f"lesson.{base}.title",
            "blurb": f"lesson.{base}.blurb",
            "summary": [key for key, _ in items] if items and all(key for key, _ in items) else None,
        }))
        for topic in topics(page, tr):
            index["topics"].append(dict(topic, file=lesson["file"], lesson=lesson["title"]))
    ui = (STATIC / "hub-ui.js").read_text(encoding="utf-8")
    for term, meaning in re.findall(r'\["([^"]+)", "([^"]+)"\]', ui):
        index["words"].append(add_tr({"term": term, "meaning": meaning}, tr, {"meaning": f"gl.{term}"}))
    return ("// Generated by scripts/build_search_index.py - do not edit by hand.\n"
            "window.HUB_SEARCH = " + json.dumps(index, indent=1, ensure_ascii=False) + ";\n")


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    content = build()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print("search-index.js is out of date: run python scripts/build_search_index.py")
            return 1
        print("search-index.js is up to date")
        return 0
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
